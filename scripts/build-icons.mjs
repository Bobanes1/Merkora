const base = new URL('../node_modules/@tabler/icons/icons/outline/', import.meta.url);
const out = {};
for (const [name, file] of Object.entries(PICK)) {
  const svg = readFileSync(new URL(file + '.svg', base), 'utf8');
  const shapes = [...svg.matchAll(/<(path|circle|rect|line|polyline|polygon|ellipse)\b([^>]*?)\/?>/g)]
    .filter((m) => !/stroke="none"/.test(m[2]))
    .map((m) => `<${m[1]}${m[2].replace(/\s+/g, ' ').trimEnd()}/>`);
  if (!shapes.length) throw new Error('no shapes in ' + file);
  out[name] = shapes.join('');
}

const src = `// Generated by scripts/build-icons.mjs – do not edit by hand.
// Icons: Tabler Icons (https://tabler.io/icons), MIT License, Copyright (c) 2020-2024 Paweł Kuna. See THIRD-PARTY-NOTICES.md.

/** Small line symbols for diagram boxes (24×24, stroke only): German name → SVG shapes. */
export const ICONS: Record<string, string> = ${JSON.stringify(out, null, 2)};

export const ICON_NAMES = Object.keys(ICONS);
`;
writeFileSync(new URL('../src/lib/diagramIcons.ts', import.meta.url), src);
